"""Deterministic synthetic *multilingual* corpus (issues #62/#68).

Real English/Japanese scans are still pending, so this module generates a
small synthetic corpus that spans zh/en/ja — including an English two-column
page and Japanese vertical pages — purely to exercise the multilingual report
and quality-gate paths in CI. Images are drawn as simple line blocks (the
default PIL font cannot render CJK glyphs, and the pixel content is irrelevant
because the oracle engine replays the answer key): these numbers measure
pipeline mechanics, never OCR accuracy, and must never be reported as accuracy.
"""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw

from scribeforge.benchmark.manifest import BenchmarkManifest, load_manifest
from scribeforge.benchmark.oracle import OracleEngine
from scribeforge.domain.ocr import PageDirection, PageOCRResult

_ZH_LINES = ("欽定四庫全書簡明目錄卷首。", "聖諭凡三葉。", "乾隆武英殿刻本。")
_EN_LINES = ("The quick brown fox jumps over the lazy dog.", "Pack my box with five dozen jugs.")
_EN_TWO_COLUMN_LINES = (
    "Left column line one.",
    "Left column line two.",
    "Right column line one.",
    "Right column line two.",
)
_JA_LINES = ("東京都は日本の首都です。", "春は曙なり。", "古池や蛙飛び込む水の音。")

#: (case id, language, direction, tags, lines)
_CASES: tuple[tuple[str, str, str, tuple[str, ...], tuple[str, ...]], ...] = (
    ("syn-zh-001", "zh", "horizontal-lr", ("synthetic", "body"), _ZH_LINES),
    ("syn-en-001", "en", "horizontal-lr", ("synthetic", "body"), _EN_LINES),
    ("syn-en-002", "en", "horizontal-lr", ("synthetic", "two-column"), _EN_TWO_COLUMN_LINES),
    ("syn-ja-001", "ja", "vertical-rl", ("synthetic", "vertical"), _JA_LINES),
    ("syn-ja-002", "ja", "vertical-rl", ("synthetic", "vertical"), _JA_LINES[::-1]),
    ("syn-zh-002", "zh", "horizontal-lr", ("synthetic", "footnote"), _ZH_LINES[::-1]),
)

_DIRECTION_TO_PAGE = {
    "horizontal-lr": PageDirection.HORIZONTAL_LR,
    "horizontal-rl": PageDirection.HORIZONTAL_RL,
    "vertical-rl": PageDirection.VERTICAL_RL,
    "vertical-lr": PageDirection.VERTICAL_LR,
}


def _draw_page(path: Path, lines: tuple[str, ...], *, vertical: bool, two_column: bool) -> None:
    """Draw a synthetic page: line blocks only (font-independent, deterministic)."""

    width, height = 640, 480
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    if two_column:
        for column in range(2):
            for row in range(len(lines) // 2):
                x = 40 + column * 300
                y = 40 + row * 60
                draw.rectangle((x, y, x + 260, y + 30), outline="black")
    elif vertical:
        for index in range(len(lines)):
            x = 600 - index * 80
            draw.rectangle((x - 50, 40, x, 440), outline="black")
    else:
        for index in range(len(lines)):
            y = 40 + index * 80
            draw.rectangle((40, y, 600, y + 40), outline="black")
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


def build_multilingual_corpus(root: Path) -> Path:
    """Write the synthetic zh/en/ja corpus under ``root``; return its manifest path."""

    cases: list[dict[str, object]] = []
    for case_id, language, direction, tags, lines in _CASES:
        image_rel = f"images/{case_id}.png"
        truth_rel = f"ground_truth/{case_id}.txt"
        _draw_page(
            root / image_rel,
            lines,
            vertical=direction.startswith("vertical"),
            two_column="two-column" in tags,
        )
        truth = root / truth_rel
        truth.parent.mkdir(parents=True, exist_ok=True)
        truth.write_text("\n".join(lines) + "\n", encoding="utf-8")
        cases.append(
            {
                "id": case_id,
                "image": image_rel,
                "ground_truth": truth_rel,
                "language": language,
                "tags": list(tags),
                "direction": direction,
                "source": (
                    "Synthetic fixture generated by "
                    "scribeforge.benchmark.multilingual_synthetic.build_multilingual_corpus; "
                    "not a scan, not an accuracy sample."
                ),
            }
        )
    manifest = {
        "schema_version": 1,
        "license": "CC0-1.0",
        "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
        "ground_truth_review_status": "single-pass",
        "ground_truth_note": (
            "Synthetic deterministic corpus generated by "
            "scribeforge.benchmark.multilingual_synthetic; reference text is generated, "
            "not transcribed from a scan. Used to exercise multilingual report paths only."
        ),
        "cases": cases,
    }
    root.mkdir(parents=True, exist_ok=True)
    manifest_path = root / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return manifest_path


def oracle_for_manifest(manifest: BenchmarkManifest, root: Path) -> OracleEngine:
    """Bind every case image to its generated answer key (oracle engine)."""

    engine = OracleEngine("oracle")
    for case in manifest.cases:
        text = (root / case.ground_truth).read_text(encoding="utf-8")
        direction = _DIRECTION_TO_PAGE.get(case.direction or "horizontal-lr")
        if direction is None:
            raise ValueError(f"unknown direction for case {case.id}: {case.direction!r}")
        engine.register(root / case.image, text, direction=direction)
    return engine


__all__ = [
    "ColumnSwappingOracle",
    "build_multilingual_corpus",
    "load_manifest",
    "oracle_for_manifest",
    "scripted_engine_for_manifest",
]


class ColumnSwappingOracle(OracleEngine):
    """Oracle that reads vertical pages' columns left-to-right (wrong order).

    The recognized *text* is perfect; only the column order is wrong. This is
    exactly the failure mode the vertical reading-order metric exists for
    (#68), so reports over this engine must show a non-zero reading-order
    error rate on vertical cases and zero on horizontal ones.
    """

    def analyze_page(self, image_path: str, page_index: int) -> PageOCRResult:
        from dataclasses import replace
        from pathlib import Path as _Path

        result = super().analyze_page(image_path, page_index)
        key = _Path(image_path).resolve()
        texts, direction = self._texts[key]
        if direction.value.startswith("vertical") and len(texts) >= 2:
            swapped = (texts[1], texts[0], *texts[2:])
            lines = tuple(replace(line, text=text) for line, text in zip(result.lines, swapped))
            return replace(result, lines=lines)
        return result


def scripted_engine_for_manifest(
    manifest: BenchmarkManifest,
    root: Path,
    *,
    name: str = "scripted",
    swap_vertical_columns: bool = False,
) -> OracleEngine:
    """Build an oracle over the corpus, optionally with scripted vertical swap."""

    engine: OracleEngine = (
        ColumnSwappingOracle(name) if swap_vertical_columns else OracleEngine(name)
    )
    for case in manifest.cases:
        text = (root / case.ground_truth).read_text(encoding="utf-8")
        direction = _DIRECTION_TO_PAGE.get(case.direction or "horizontal-lr")
        if direction is None:
            raise ValueError(f"unknown direction for case {case.id}: {case.direction!r}")
        engine.register(root / case.image, text, direction=direction)
    return engine

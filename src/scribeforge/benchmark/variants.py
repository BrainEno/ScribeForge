"""Deterministic synthetic A/B/C/D variant comparison (issue #81).

The historical benchmark report could only score single-engine variants, so
the benefit of the dual-engine pipeline (C) and the VLM review (D) had no
measured data. This module closes that gap without real OCR runtimes: a
seeded synthetic corpus plus scripted engines make the four-variant
comparison reproducible by anyone, and the numbers it produces are pipeline
mechanism measurements, not OCR accuracy claims.

Design:

- Every synthetic page shares the same reference lines, so a scripted VLM
  reviewer can answer by pair index alone (each benchmark case runs in its own
  project with page index 0).
- The primary scripted engine misreads a fixed set of line indexes; the
  secondary engine reads the reference verbatim.
- Therefore variant C must accept only corroborated (correct) lines and leave
  the disputed ones unresolved, with zero false accepts; variant D, with a VLM
  that corroborates the secondary engine, resolves those disputes correctly.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, replace
from pathlib import Path

from PIL import Image, ImageDraw

from scribeforge.benchmark.manifest import BenchmarkManifest, load_manifest
from scribeforge.benchmark.oracle import OracleEngine
from scribeforge.benchmark.pipeline_runner import run_pipeline_benchmark
from scribeforge.benchmark.runner import BenchmarkReport, run_benchmark
from scribeforge.domain.ocr import PageOCRResult
from scribeforge.domain.vlm import VLMReading, VLMReviewer

PAGES = 6
LINES_PER_PAGE = 8
#: Line indexes (within a page) the primary scripted engine misreads.
CORRUPTED_LINE_INDEXES: tuple[int, ...] = (1, 5)


def _page_lines() -> tuple[str, ...]:
    return tuple(
        f"shared line {index} the quick brown fox jumps" for index in range(LINES_PER_PAGE)
    )


def build_synthetic_corpus(root: Path) -> Path:
    """Write the deterministic synthetic corpus under ``root``; return its manifest."""

    lines = _page_lines()
    (root / "images").mkdir(parents=True, exist_ok=True)
    (root / "ground_truth").mkdir(parents=True, exist_ok=True)
    cases = []
    for page in range(PAGES):
        image_path = root / "images" / f"page-{page:03d}.png"
        image = Image.new("RGB", (640, 480), "white")
        draw = ImageDraw.Draw(image)
        for row, text in enumerate(lines):
            draw.text((40, 30 + row * 50), text, fill="black")
        draw.text((600, 10), str(page), fill="black")  # keep page digests unique
        image.save(image_path)
        truth_path = root / "ground_truth" / f"case-{page:03d}.txt"
        truth_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        cases.append(
            {
                "id": f"synthetic-{page:03d}",
                "image": f"images/page-{page:03d}.png",
                "ground_truth": f"ground_truth/case-{page:03d}.txt",
                "language": "en",
                "tags": ["synthetic", "body"],
                "direction": "horizontal-lr",
            }
        )
    manifest_path = root / "manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "ground_truth_review_status": "single-pass",
                "ground_truth_note": (
                    "Synthetic deterministic corpus generated by "
                    "scribeforge.benchmark.variants.build_synthetic_corpus; the reference "
                    "text is generated, not transcribed from a scan."
                ),
                "cases": cases,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return manifest_path


class CorruptingEngine(OracleEngine):
    """An oracle engine that misreads a fixed set of line indexes."""

    def __init__(self, name: str, error_indexes: tuple[int, ...]) -> None:
        super().__init__(name)
        self._error_indexes = frozenset(error_indexes)

    def analyze_page(self, image_path: str, page_index: int) -> PageOCRResult:
        result = super().analyze_page(image_path, page_index)
        lines = []
        for index, line in enumerate(result.lines):
            if index in self._error_indexes and line.text:
                lines.append(replace(line, text=line.text[:-1] + "X"))
            else:
                lines.append(line)
        return replace(result, lines=tuple(lines))


class CorroboratingReviewer(VLMReviewer):
    """A scripted vision model that corroborates the perfect secondary engine.

    Since issue #76 a VLM answer is only accepted when it matches one engine,
    so this reviewer returns the reference line for the requested pair — the
    reading the secondary engine produced.
    """

    def transcribe_crop(self, image_path: str, page_index: int, pair_index: int) -> VLMReading:
        del image_path  # the synthetic crop carries no evidence the script needs
        lines = _page_lines()
        if not 0 <= pair_index < len(lines):
            return VLMReading(page_index, pair_index, "synthetic-vlm", "1", "", True)
        return VLMReading(page_index, pair_index, "synthetic-vlm", "1", lines[pair_index], False)


def scripted_engines(root: Path, manifest: BenchmarkManifest) -> tuple[OracleEngine, OracleEngine]:
    """Build the (primary, secondary) scripted engine pair for a synthetic corpus."""

    primary = CorruptingEngine("mineru", CORRUPTED_LINE_INDEXES)
    secondary = OracleEngine("paddleocr")
    for case in manifest.cases:
        image = (root / case.image).resolve()
        text = (root / case.ground_truth).read_text(encoding="utf-8")
        primary.register(image, text)
        secondary.register(image, text)
    return primary, secondary


@dataclass(frozen=True, slots=True)
class VariantComparison:
    """The four benchmark variants measured over one corpus."""

    reports: tuple[BenchmarkReport, ...]

    def by_engine(self, name: str) -> BenchmarkReport:
        for report in self.reports:
            if report.engine == name:
                return report
        raise KeyError(name)


def run_variant_comparison(root: Path, manifest_path: Path) -> VariantComparison:
    """Run variants A, B, C and D over the synthetic corpus at ``root``."""

    manifest = load_manifest(manifest_path)
    primary, secondary = scripted_engines(root, manifest)
    return VariantComparison(
        reports=(
            run_benchmark(manifest, root, primary),
            run_benchmark(manifest, root, secondary),
            run_pipeline_benchmark(manifest, root, primary, secondary),
            run_pipeline_benchmark(
                manifest, root, primary, secondary, reviewer=CorroboratingReviewer()
            ),
        )
    )
